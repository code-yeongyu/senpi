import { spawn } from "node:child_process";
import { connect } from "node:net";
import { mkdtempSync, mkdirSync, rmSync } from "node:fs";
import { join } from "node:path";
const sandbox = mkdtempSync("/tmp/dh-s"); const agentDir = join(sandbox, "a"); mkdirSync(agentDir, { recursive: true });
const sessionDir = join(sandbox, "s"); mkdirSync(sessionDir, { recursive: true });
const socket = join(sandbox, "h.sock");
const env = { ...process.env, SENPI_CODING_AGENT_DIR: agentDir };
for (const k of ["OMO_RPC_SOCKET_PATH","SENPI_RPC_HOST_WATCH_FD","OMO_RPC_SOCKET","SENPI_RPC_SOCKET","PI_RPC_SOCKET"]) delete env[k];
const host = spawn("bun", ["packages/coding-agent/src/cli.ts","--mode","rpc","--multi-session","--listen","unix://"+socket,"--no-extensions","--no-skills","--no-prompt-templates"], { env, stdio: ["ignore","pipe","pipe"] });
let ready = false; host.stderr.on("data", (b) => { if (String(b).includes("listening")) ready = true; });
const wait = async (f, ms=30000) => { const t0=Date.now(); while (Date.now()-t0<ms) { if (await f()) return true; await new Promise(r=>setTimeout(r,100)); } return false; };
await wait(async()=>ready);
const sock = connect(socket); await new Promise(r=>sock.once("connect",r));
let buf=""; const pend=new Map();
sock.on("data",(b)=>{buf+=b;let i;while((i=buf.indexOf("\n"))>=0){const l=buf.slice(0,i);buf=buf.slice(i+1);if(!l.trim())continue;try{const m=JSON.parse(l);if(m.id&&pend.has(m.id)){pend.get(m.id)(m);pend.delete(m.id);}}catch{}}});
const req=(m)=>new Promise(r=>{pend.set(m.id,r);sock.write(JSON.stringify(m)+"\n");});
const run=(c)=>new Promise(res=>{const p=spawn("sh",["-c",c]);let o="";p.stdout.on("data",b=>o+=b);p.on("close",()=>res(o.trim()));});
const threads=async()=>Number(await run(`ps -M ${host.pid} | tail -n +2 | wc -l | tr -d ' '`));
console.log("threads@0=", await threads());
for (let i=1;i<=20;i++) await req({id:"o"+i,type:"open_session",cwd:sandbox,sessionPath:join(sessionDir,"s"+i+".jsonl")});
console.log("threads@20=", await threads());
await run(`sample ${host.pid} 2 -file /tmp/dh-sample.txt >/dev/null 2>&1`);
const top = await run(`rg -o "^ *[0-9]+ [A-Za-z_:<>~\\-]+" /tmp/dh-sample.txt | head -0; grep -A3 "^Thread" /tmp/dh-sample.txt | rg -o "[A-Za-z_][A-Za-z0-9_:]{6,}" | sort | uniq -c | sort -rn | head -14`);
console.log("--- sampled frame names\n" + top);
sock.destroy(); host.kill("SIGTERM"); await new Promise(r=>setTimeout(r,1200)); rmSync(sandbox,{recursive:true,force:true});
