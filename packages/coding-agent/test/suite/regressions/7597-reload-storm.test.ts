// The default bound on one session's hold of the reload queue (config-reload `RELOAD_SLOT_TIMEOUT_MS`).
const RELOAD_SLOT_BOUND_MS = 60_000;
const roots: string[] = [];
const sessions: Harness[] = [];
// Every reload a test leaves open; afterEach settles them so the process-wide queue is empty for the next test.
const openReloads: Array<PromiseWithResolvers<void>> = [];

function fixture() {
	const root = mkdtempSync(join(tmpdir(), "reload-storm-"));
	roots.push(root);
	const extensionDir = join(root, "extensions");
	mkdirSync(extensionDir);
	return { root, extensionDir, shim: join(extensionDir, "diff.js") };
}

async function settleOpenReloads(): Promise<void> {
	for (let index = 0; index < openReloads.length; index++) {
		openReloads[index]?.resolve();
		await vi.advanceTimersByTimeAsync(0);
	}
	openReloads.length = 0;
}

afterEach(async () => {
	if (vi.isFakeTimers()) await settleOpenReloads();
	for (const session of sessions.splice(0).reverse()) session.cleanup();
	vi.useRealTimers();
	vi.restoreAllMocks();
	vi.unstubAllEnvs();
	for (const root of roots.splice(0)) rmSync(root, { recursive: true, force: true });
});

const FOREIGN_BANNER =
	"// Generated by Other.Product. Delete this file to stop loading the default global extension.\n";

/** Seed and load the default extensions of an agent directory, as a session start does. */
async function loadDefaults(root: string) {
	vi.stubEnv("SENPI_CODING_AGENT_DIR", root);
	const loader = new DefaultResourceLoader({ cwd: root, agentDir: root });
	await loader.reload();
	return loader;
}

// #7597, #7599 review: a generated shim marks an installed default. Its code is always this process's own builtin, and
// a shim another installation wrote for its live builtin is left alone so two installations stop rewriting it.
it("loads this process's builtin for another installation's shim and leaves the shim alone", async () => {
	const { root, shim } = fixture();
	const builtin = join(root, "another-version", "dist", "core", "extensions", "builtin");
	mkdirSync(builtin, { recursive: true });
	const target = join(builtin, "diff.js");
	writeFileSync(
		target,
		'globalThis[Symbol.for("senpi-7597-foreign-diff")] = true;\nexport default function diff() {}\n',
	);
	const content = FOREIGN_BANNER + `export { default } from ${JSON.stringify(pathToFileURL(target).href)};\n`;
	writeFileSync(shim, content);
	const inProcess = vi.spyOn(globalDefaultExtensionFactories, "diff");
	const loader = await loadDefaults(root);
	expect(loader.getExtensions().errors).toEqual([]);
	expect(inProcess).toHaveBeenCalled();
	expect(Reflect.get(globalThis, Symbol.for("senpi-7597-foreign-diff"))).toBeUndefined();
	expect(readFileSync(shim, "utf8")).toBe(content);
});

it("repairs another installation's shim whose builtin is gone", async () => {
	const { root, shim } = fixture();
	const missing = join(root, "removed-version", "dist", "core", "extensions", "builtin", "diff.js");
	writeFileSync(shim, FOREIGN_BANNER + `export { default } from ${JSON.stringify(pathToFileURL(missing).href)};\n`);
	const inProcess = vi.spyOn(globalDefaultExtensionFactories, "diff");
	const loader = await loadDefaults(root);
	const repaired = readFileSync(shim, "utf8");
	expect(repaired.startsWith(GENERATED_SHIM_BANNER)).toBe(true);
	expect(repaired).not.toContain("removed-version");
	expect(loader.getExtensions().errors).toEqual([]);
	expect(inProcess).toHaveBeenCalled();
});

it("loads a user's file that starts with the generated banner as the user's own extension", async () => {
	const { root, shim } = fixture();
	const content =
		GENERATED_SHIM_BANNER +
		'globalThis[Symbol.for("senpi-7597-user-diff")] = true;\nexport default function diff() {}\n';
	writeFileSync(shim, content);
	const inProcess = vi.spyOn(globalDefaultExtensionFactories, "diff");
	const loader = await loadDefaults(root);
	expect(loader.getExtensions().errors).toEqual([]);
	expect(Reflect.get(globalThis, Symbol.for("senpi-7597-user-diff"))).toBe(true);
	expect(inProcess).not.toHaveBeenCalled();
	expect(readFileSync(shim, "utf8")).toBe(content);
});

/** Sessions sharing one extensions directory. Each reload stays open until the test settles it. */
async function watchers(starts: ReadonlyArray<SessionStartEvent | undefined>, logger?: ConfigReloadLogger) {
	vi.useFakeTimers();
	const { root, extensionDir, shim } = fixture();
	writeFileSync(shim, GENERATED_SHIM_BANNER + 'export { default } from "file:///old/diff.js";\n');
	const listeners = new Set<WatchEventListener>();
	const calls: number[] = [];
	let active = 0;
	let peak = 0;
	for (const [index, sessionStartEvent] of starts.entries()) {
		const session = await createHarness({
			siblingOf: sessions[0],
			persistSession: true,
			...(sessionStartEvent ? { sessionStartEvent } : {}),
			extensionFactories: [
				(pi) =>
					configReloadExtension(pi, {
						agentDir: root,
						clock: { setTimeout, clearTimeout },
						...(logger ? { logger } : {}),
						subscribe: (path, listener) => {
							if (path === extensionDir) listeners.add(listener);
							return () => {
								listeners.delete(listener);
							};
						},
					}),
			],
		});
		sessions.push(session);
		await session.session.bindExtensions({
			mode: "rpc",
			commandContextActions: {
				waitForIdle: () => session.session.waitForIdle(),
				newSession: async () => ({ cancelled: false }),
				fork: async () => ({ cancelled: false }),
				navigateTree: async () => ({ cancelled: false }),
				editAssistantMessage: async () => ({ cancelled: false }),
				editUserMessage: async () => ({ cancelled: false }),
				switchSession: async () => ({ cancelled: false }),
				reload: async () => {
					const open = Promise.withResolvers<void>();
					openReloads.push(open);
					calls.push(index);
					peak = Math.max(peak, ++active);
					await open.promise;
					active--;
				},
			},
		});
	}
	return {
		calls,
		peak: () => peak,
		async rewrite(content: string) {
			writeFileSync(shim, content);
			for (const listener of listeners) listener("change", "diff.js");
			await vi.advanceTimersByTimeAsync(200);
		},
	};
}

it("suppresses another product's generated shim and still reloads an authored replacement", async () => {
	const group = await watchers([undefined]);
	await group.rewrite(
		'// Generated by Other.Product. Delete this file to stop loading the default global extension.\nexport { default } from "file:///new/diff.js";\n',
	);
	expect(group.calls).toEqual([]);
	await group.rewrite("// Generated by senpi. Hand-maintained extension.\nexport default () => {};\n");
	expect(group.calls).toEqual([0]);
});

// #7599 review: a session started with no client attached reloads through the queue like any other.
it("delivers a user edit once to every session, attended or not, with one reload in flight", async () => {
	const group = await watchers([{ type: "session_start", reason: "startup", attended: false }, undefined, undefined]);
	await group.rewrite("export default () => {};\n");
	expect(group.calls).toEqual([0]);
	await settleOpenReloads();
	expect(group.calls).toEqual([0, 1, 2]);
	expect(group.peak()).toBe(1);
});

// #7599 review: one reload that never settles must not stop watcher reloads for every other session.
it("releases the queue slot after the bound while a reload that never settles keeps running", async () => {
	const warnings: string[] = [];
	const status = { written: false, disabled: true };
	const logger: ConfigReloadLogger = {
		debug: () => status,
		info: () => status,
		warn: (event) => {
			warnings.push(event);
			return status;
		},
		error: () => status,
	};
	const group = await watchers([undefined, undefined], logger);
	await group.rewrite("export default () => {};\n");
	expect(group.calls).toEqual([0]);
	await vi.advanceTimersByTimeAsync(RELOAD_SLOT_BOUND_MS - 1);
	expect(group.calls).toEqual([0]);
	await vi.advanceTimersByTimeAsync(1);
	expect(group.calls).toEqual([0, 1]);
	expect(group.peak()).toBe(2);
	expect(warnings).toEqual(["reload_slot_released"]);
});

// #7599 review: a session closed while it waits for the queue gives its turn up.
it("frees the queue for the next session when a queued session closes", async () => {
	const group = await watchers([undefined, undefined, undefined]);
	await group.rewrite("export default () => {};\n");
	expect(group.calls).toEqual([0]);
	await sessions[1].getExtensionRunner().emit({ type: "session_shutdown", reason: "quit" });
	await settleOpenReloads();
	expect(group.calls).toEqual([0, 2]);
});

// #7599 review: a reload the reloaded session requests from its own session_start waits its turn instead of
// waiting on the reload that is running it.
// A real reload replaces the extension instance, so this drives instances directly as the config-reload owner tests do.
it("queues a follow-up requested during a session's reload behind the other sessions", async () => {
	vi.useFakeTimers();
	const { root } = fixture();
	const settings = join(root, "settings.json");
	writeFileSync(settings, JSON.stringify({ theme: "dark" }));
	const bus = createEventBus();
	const listeners = new Set<WatchEventListener>();
	const options = {
		agentDir: root,
		clock: { setTimeout, clearTimeout },
		subscribe: (path: string, listener: WatchEventListener) => {
			if (path === root) listeners.add(listener);
			return () => {
				listeners.delete(listener);
			};
		},
	};
	const instance = () => {
		const handlers = new Map<string, (event: unknown, ctx: ExtensionContext) => unknown>();
		configReloadExtension({ events: bus, on: handlers.set.bind(handlers) } as unknown as ExtensionAPI, options);
		return (event: SessionStartEvent | SessionShutdownEvent, ctx: ExtensionContext) =>
			handlers.get(event.type)?.(event, ctx);
	};
	const calls: string[] = [];
	let active = 0;
	let peak = 0;
	const context = (name: string, duringReload?: () => Promise<void>) =>
		({
			cwd: root,
			mode: "tui",
			ui: { notify: () => {} },
			isIdle: () => true,
			hasPendingMessages: () => false,
			isProjectTrusted: () => true,
			isCompacting: () => false,
			requestReload: async () => {
				const open = Promise.withResolvers<void>();
				openReloads.push(open);
				calls.push(name);
				peak = Math.max(peak, ++active);
				await duringReload?.();
				await open.promise;
				active--;
			},
		}) as unknown as ExtensionContext;
	const a = instance();
	const aContext = context("a", async () => {
		await a({ type: "session_shutdown", reason: "reload" }, aContext);
		writeFileSync(settings, JSON.stringify({ theme: "changed during the reload" }));
		await instance()({ type: "session_start", reason: "reload" }, context("a follow-up"));
	});
	await a({ type: "session_start", reason: "startup" }, aContext);
	await instance()({ type: "session_start", reason: "startup" }, context("b"));
	writeFileSync(settings, JSON.stringify({ theme: "light" }));
	for (const listener of listeners) listener("change", "settings.json");
	await vi.advanceTimersByTimeAsync(200);
	expect(calls).toEqual(["a"]);
	await settleOpenReloads();
	expect([...calls].sort()).toEqual(["a", "a follow-up", "b"]);
	expect(peak).toBe(1);
});
