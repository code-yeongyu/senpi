import { fileURLToPath } from "node:url";
import { APP_NAME } from "../config.ts";

/**
 * Banner written at the top of the generated global-default extension shim.
 *
 * The config-reload watcher recognises its own generated shims by this banner. A rebranded
 * install writes its own product name, so every banner a machine may already carry stays
 * recognised - otherwise those files would look user-authored and retrigger reload loops.
 */
export const GENERATED_SHIM_BANNER = `// Generated by ${APP_NAME}. Delete this file to stop loading the default global extension.\n`;

const GENERATED_FIRST_LINE =
	/^\/\/ Generated by [^\r\n]+\. Delete this file to stop loading the default global extension\.(?:\r?\n|$)/;
const GENERATED_EXPORT = /^export \{ default \} from ("[^"\r\n]*");(?:\r?\n)?$/;

export function hasGeneratedShimBanner(content: string): boolean {
	return GENERATED_FIRST_LINE.test(content);
}

/**
 * The single `file:` re-export written by the seed step. Additional user code, or any other specifier, makes this a
 * normal extension: the module loader resolves a relative specifier against the file itself, so judging it here
 * against this process's working directory would classify the same file differently per session (senpi#7625).
 */
export function generatedShimTarget(content: string): string | undefined {
	if (!hasGeneratedShimBanner(content)) return undefined;
	const specifier = GENERATED_EXPORT.exec(content.slice(content.indexOf("\n") + 1))?.[1];
	if (specifier === undefined) return undefined;
	try {
		const target: string = JSON.parse(specifier);
		return target.startsWith("file:") ? fileURLToPath(target) : undefined;
	} catch {
		return undefined;
	}
}
